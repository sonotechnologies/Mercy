/**
 * Builds supabase/setup.sql: the schema plus the current demo catalogue, sale, settings
 * and the admin email. Paste the result into the Supabase SQL editor and run it.
 *
 *   npx tsx scripts/build-setup-sql.ts --admin-email mercy@gmail.com
 *
 * Products are inserted with "on conflict do nothing", so re-running never overwrites
 * products edited in the admin.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { productToRow } from "../src/lib/backend/mappers";
import { SEED_PRODUCTS, SEED_SALE, SEED_SETTINGS } from "../src/lib/seed";

const root = path.resolve(import.meta.dirname, "..");
const i = process.argv.indexOf("--admin-email");
const adminEmail = i > -1 ? process.argv[i + 1] : "";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const ints = (a: number[]) => `'{${a.join(",")}}'::integer[]`;

const products = SEED_PRODUCTS.map((p, idx) => {
  const r = productToRow(p, idx);
  return `  (${[q(r.id), q(r.slug), q(r.name), q(r.gender), q(r.style), q(r.price), q(r.sale_price), json(r.colours), ints(r.sizes), ints(r.sold_out_sizes), q(r.in_stock), q(r.is_new), q(r.is_bestseller), q(r.description), q(r.focus), q(r.order_type), q(r.production_time), q(r.sort), q(r.created_at)].join(", ")})`;
});
const images = SEED_PRODUCTS.flatMap((p) => p.images.map((u, pos) => `  (${q(p.id)}, ${q(u)}, ${pos})`));

const sql = `${readFileSync(path.join(root, "supabase/schema.sql"), "utf8").trim()}

-- ---------------------------------------------------------------------------
-- Starting data (generated by scripts/build-setup-sql.ts). Existing rows are kept.
-- ---------------------------------------------------------------------------

insert into public.products (id, slug, name, gender, style, price, sale_price, colours, sizes, sold_out_sizes, in_stock, is_new, is_bestseller, description, focus, order_type, production_time, sort, created_at) values
${products.join(",\n")}
on conflict (id) do nothing;

insert into public.product_images (product_id, url, position)
select v.product_id, v.url, v.position from (values
${images.join(",\n")}
) as v(product_id, url, position)
where not exists (select 1 from public.product_images pi where pi.product_id = v.product_id);

insert into public.settings (key, value) values
  ('settings', ${json(SEED_SETTINGS)}),
  ('sale', ${json(SEED_SALE)})
on conflict (key) do nothing;
${adminEmail ? `\ninsert into public.admin_users (email) values (${q(adminEmail.toLowerCase())}) on conflict do nothing;\n` : ""}`;

writeFileSync(path.join(root, "supabase/setup.sql"), sql);
console.log(`Wrote supabase/setup.sql (${SEED_PRODUCTS.length} products${adminEmail ? `, admin ${adminEmail.toLowerCase()}` : ""})`);
